import fs from "node:fs";
import { WebSocket } from "ws";

const port = Number(process.argv[2]);
const outputPath = process.argv[3];
if (!Number.isInteger(port) || !outputPath) throw new Error("Usage: node accept-native-research-create.mjs <port> <output.json>");
const pages = (await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()).filter((item) => item.type === "page");
if (pages.length !== 1) throw new Error(`Expected one native page, got ${pages.length}`);
const page = pages[0];
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((resolve, reject) => { ws.once("open", resolve); ws.once("error", reject); });
let id = 0;
const pending = new Map();
ws.on("message", (raw) => {
  const msg = JSON.parse(raw.toString());
  const item = pending.get(msg.id);
  if (!item) return;
  pending.delete(msg.id);
  msg.error ? item.reject(new Error(JSON.stringify(msg.error))) : item.resolve(msg.result);
});
const call = (method, params = {}) => new Promise((resolve, reject) => {
  const callId = ++id;
  pending.set(callId, { resolve, reject });
  ws.send(JSON.stringify({ id: callId, method, params }));
});
const evaluate = async (expression) => {
  const result = await call("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true });
  if (result.exceptionDetails) throw new Error(result.exceptionDetails.text);
  return result.result?.value;
};
await call("Runtime.enable");
