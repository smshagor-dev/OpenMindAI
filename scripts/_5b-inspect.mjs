import { WebSocket } from "ws";
const port=Number(process.argv[2]);
const pages=(await(await fetch(`http://127.0.0.1:${port}/json/list`)).json()).filter(t=>t.type==="page");
const s=new WebSocket(pages[0].webSocketDebuggerUrl); await new Promise((r,j)=>{s.once("open",r);s.once("error",j);});
let id=0;const p=new Map();s.on("message",raw=>{const m=JSON.parse(raw);const w=p.get(m.id);if(!w)return;p.delete(m.id);m.error?w.rej(new Error(JSON.stringify(m.error))):w.res(m.result);});
const call=(m,pr={})=>new Promise((r,j)=>{const i=++id;p.set(i,{res:r,rej:j});s.send(JSON.stringify({id:i,method:m,params:pr}));});
const ev=async e=>{const r=await call("Runtime.evaluate",{expression:`(async()=>{${e}})()`,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw new Error(JSON.stringify(r.exceptionDetails));return r.result?.value;};
await call("Runtime.enable");
const out=await ev(`
  const invoke=window.__TAURI_INTERNALS__.invoke;
  const proj=(await invoke('list_local_research_projects'))[0];
  const sections=await invoke('list_local_research_sections',{projectId:proj.id});
  const results=sections.filter(x=>x.sectionKey==='results').sort((a,b)=>b.revision-a.revision)[0];
  const ledger=(await invoke('local_research_claim_ledger',{projectId:proj.id})).filter(l=>l.sectionDraftId===results.id);
  return {content:results.content, validation:results.validation, contentSha256:results.contentSha256, ledger:ledger.map(l=>({v:l.renderedToken,fact:l.factId,metric:l.metric,value:l.valueText,sha:l.documentSha256.slice(0,12),locator:l.locator,method:l.method.slice(0,40)}))};
`);
console.log("=== RESULTS CONTENT ==="); console.log(out.content);
console.log("\n=== VALIDATION ==="); console.log(JSON.stringify(out.validation,null,2));
console.log("\n=== LEDGER ("+out.ledger.length+" rows) ==="); for(const r of out.ledger) console.log(`${r.v??'(qual)'} -> ${r.fact} ${r.metric}=${r.value} @${r.sha} | ${r.locator}`);
import('node:fs').then(fs=>fs.writeFileSync('artifacts/acceptance/test6-2026-11-23/milestone-5b/generation/results-content-ledger.json',JSON.stringify(out,null,2)));
s.close();
